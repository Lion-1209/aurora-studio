/**
 * Generate `src/05-pet-image.js` from the licensed transparent artwork in
 * `assets/`.
 *
 * The Client bundle cannot load package-local image files at runtime (there is
 * no asset URL plumbing for plain-JS bundle plugins), so the character art is
 * inlined as data URLs. Run after replacing the source images:
 *
 *   node tools/build-pet-images.mjs
 *
 * Artwork: `assets/whale-girl-open.webp` / `-closed.webp`, derived (cropped,
 * split into open/closed-eye frames, resized and re-encoded) from the
 * transparent character art of YunYueSama/codex-deepseek-pet, used under the
 * "大肥鱼项目署名许可 1.0" — see `assets/ATTRIBUTION.md` and
 * `assets/LICENSE-codex-deepseek-pet.txt`.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const open = readFileSync(new URL('assets/whale-girl-open.webp', root)).toString('base64')
const closed = readFileSync(new URL('assets/whale-girl-closed.webp', root)).toString('base64')

/** Split a base64 payload into concatenated JS string chunks. */
function chunks(payload, size) {
  const parts = []
  for (let index = 0; index < payload.length; index += size) {
    parts.push("  '" + payload.slice(index, index + size) + "'")
  }
  return parts.join(' +\n')
}

const source = `/* -------------------------------------------------------------------------
 * Aurora Studio · 大肥鱼 (DeepSeek whale girl) character art
 * GENERATED by tools/build-pet-images.mjs — do not edit by hand.
 *
 * Transparent open-eye / closed-eye frames + walk/idle/wave/jump animation
 * strips, inlined as data URLs because a plain-JS bundle plugin has no runtime
 * asset resolution. Artwork credits and license: assets/ATTRIBUTION.md +
 * assets/LICENSE-codex-deepseek-pet.txt.
 * ---------------------------------------------------------------------- */

const PET_IMAGE_DEEPSEEK_OPEN =
  'data:image/webp;base64,' +
${chunks(open, 120)}

const PET_IMAGE_DEEPSEEK_CLOSED =
  'data:image/webp;base64,' +
${chunks(closed, 120)}
`

writeFileSync(new URL('src/05-pet-image.js', root), source)
console.log('build-pet-images: wrote src/05-pet-image.js (' + source.length + ' chars)')

/* ---------------------------------------------------------- animation strips */

const SPRITES = [
  { name: 'idle', file: 'assets/sprite-idle.webp', frames: 6, duration: 2600 },
  { name: 'walk', file: 'assets/sprite-walk.webp', frames: 8, duration: 900 },
  { name: 'wave', file: 'assets/sprite-wave.webp', frames: 4, duration: 1100 },
  { name: 'jump', file: 'assets/sprite-jump.webp', frames: 5, duration: 900 },
]

const spriteParts = []
for (const sprite of SPRITES) {
  const base64 = readFileSync(new URL(sprite.file, root)).toString('base64')
  spriteParts.push(
    "const PET_SPRITE_" + sprite.name.toUpperCase() + " =\n  'data:image/webp;base64,' +\n" + chunks(base64, 120)
  )
}

const spriteSource = `/* -------------------------------------------------------------------------
 * Aurora Studio · 大肥鱼 animation strips
 * GENERATED by tools/build-pet-images.mjs — do not edit by hand.
 *
 * Horizontal strips cropped from the licensed Codex pet sprite sheet
 * (codex-deepseek-pet/spritesheet-web.webp); frames are 140x160 WebP tiles.
 * ---------------------------------------------------------------------- */

const PET_SPRITE_FRAME = { width: 160, height: 160 }

${spriteParts.join('\n\n')}

const PET_SPRITE_ACTIONS = {
  idle: { frames: 6, duration: 2600 },
  walk: { frames: 8, duration: 900 },
  wave: { frames: 4, duration: 1100 },
  jump: { frames: 5, duration: 900 },
}
`

writeFileSync(new URL('src/07-pet-sprites.js', root), spriteSource)
console.log('build-pet-images: wrote src/07-pet-sprites.js (' + spriteSource.length + ' chars)')

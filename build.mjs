/**
 * Build `client.js` (the browser artifact) from the fragments in `src/`.
 *
 * The fragments share ONE factory scope: they are concatenated in order inside
 * `window.__ModuleLoader__.load({ id, factory(require) { ... } })`. This keeps
 * the plugin a single plain-JS module with no bundler and no extra runtime
 * dependencies beyond `react`.
 *
 * Run:  node build.mjs
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const PARTS = [
  'src/00-core.js',
  'src/05-pet-image.js',
  'src/07-pet-sprites.js',
  'src/10-store.js',
  'src/12-account.js',
  'src/20-theme.js',
  'src/25-background.js',
  'src/40-pet-art.js',
  'src/42-pet-sprite.js',
  'src/44-pet-account.js',
  'src/45-pet.js',
  'src/50-settings-view.js',
  'src/55-settings-css.js',
  'src/90-apply.js',
]

const root = new URL('./', import.meta.url)
const missing = PARTS.filter((part) => !existsSync(new URL(part, root)))
if (missing.length > 0) {
  console.error('build: missing fragment(s):')
  for (const part of missing) console.error('  - ' + part)
  process.exit(1)
}

const body = PARTS.map((part) => {
  const source = readFileSync(new URL(part, root), 'utf8')
  return `// ---- ${part} ----\n${source.trim()}\n`
}).join('\n')

const artifact = `/* Generated by build.mjs — do not edit. */
window.__ModuleLoader__.load({
  id: '@local/aurora-studio',
  factory(require) {
    const React = require('react');
    const h = React.createElement;

${body}
    return { inject: ['slots', 'theme', 'locale', 'remote', 'remote.account', 'sessions'], apply };
  },
});
`

writeFileSync(new URL('client.js', root), artifact)
console.log('build: wrote client.js (' + artifact.length + ' bytes, ' + artifact.split('\n').length + ' lines)')
